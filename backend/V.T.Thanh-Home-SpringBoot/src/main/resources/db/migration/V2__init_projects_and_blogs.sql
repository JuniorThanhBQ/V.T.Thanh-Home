CREATE TABLE IF NOT EXISTS projects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug VARCHAR(120) NOT NULL UNIQUE,
    label VARCHAR(50),
    title VARCHAR(160) NOT NULL,
    subtitle VARCHAR(240),
    description TEXT NOT NULL,
    github_link VARCHAR(500),
    website_link VARCHAR(500),
    display_order INT NOT NULL DEFAULT 0,
    published BOOLEAN NOT NULL DEFAULT TRUE,
    version BIGINT NOT NULL DEFAULT 0,
    created_date TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_date TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE IF NOT EXISTS project_tech_stacks (
    project_id BIGINT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    tech_name VARCHAR(50) NOT NULL,
    position INT NOT NULL,
    PRIMARY KEY (project_id, position)
);

CREATE TABLE IF NOT EXISTS blogs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug VARCHAR(120) NOT NULL UNIQUE,
    title VARCHAR(160) NOT NULL,
    subtitle VARCHAR(240),
    description TEXT NOT NULL,
    category VARCHAR(50) NOT NULL,
    banner_url VARCHAR(500),
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    published_at TIMESTAMP WITH TIME ZONE,
    version BIGINT NOT NULL DEFAULT 0,
    created_date TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_date TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE IF NOT EXISTS blog_chapters (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    blog_id BIGINT NOT NULL REFERENCES blogs(id) ON DELETE CASCADE,
    title VARCHAR(160) NOT NULL,
    content TEXT NOT NULL,
    chapter_order INT NOT NULL,
    created_date TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_date TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_blog_chapter_order UNIQUE (blog_id, chapter_order)
);

CREATE INDEX IF NOT EXISTS idx_projects_published_order ON projects(published, display_order, id);
CREATE INDEX IF NOT EXISTS idx_blogs_status_published_at ON blogs(status, published_at DESC, id);
CREATE INDEX IF NOT EXISTS idx_blog_chapters_blog_order ON blog_chapters(blog_id, chapter_order);
